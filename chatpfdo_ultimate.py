    def analyze_question(self, text):
        """Максимально точный анализ"""
        text_lower = text.lower().strip()
        
        # Приветствие
        if any(word in text_lower for word in self.knowledge["приветствия"]):
            return "greeting", None
        
        # Прощание
        if any(word in text_lower for word in self.knowledge["прощания"]):
            return "farewell", None
        
        # Вопросы о ПФДО (по длинным сначала)
        for question, answer in sorted(self.knowledge["вопросы_о_пфдо"].items(), key=lambda x: -len(x[0])):
            if question in text_lower:
                return "pfdo_question", answer
        
        # Дополнительно
        for key, answer in self.knowledge["дополнительно"].items():
            if key in text_lower:
                return "additional", answer
        
        # ИНН
        inn_match = re.search(r'\b\d{10}\b|\b\d{12}\b', text)
        if inn_match or "инн" in text_lower:
            return "check_inn", inn_match.group() if inn_match else None
        
        # Направления (по длинным сначала)
        for dir_key, dir_name in sorted(self.knowledge["направления"].items(), key=lambda x: -len(x[0])):
            if dir_key in text_lower:
                return "search_direction", dir_key
        
        # Поиск
        if any(w in text_lower for w in ["найди", "поиск", "покажи", "search", "где", "ищу"]):
            query = re.sub(r'(найди|поиск|покажи|search|где|ищу)\s*', '', text_lower).strip()
            return "search", query
        
        # Список
        if any(w in text_lower for w in ["список", "все организации", "перечень", "каталог"]):
            return "list", None
        
        # Статус
        if "статус" in text_lower:
            return "status", None
        
        # Помощь
        if any(w in text_lower for w in ["помощь", "умеешь", "help", "команды", "что ты", "возможности"]):
            return "help", None
        
        return "search", text_lower
    
    def get_organizations(self, search=None, page=1, limit=10):
        try:
            params = {"page": page, "per-page": limit}
            if search:
                params["search"] = search
            response = self.session.get(f"{self.base_url}/organizations", params=params, timeout=10)
            if response.status_code == 200:
                return response.json().get("data", [])
            return []
        except:
            return []
    
    def get_org_by_inn(self, inn):
        try:
            response = self.session.get(f"{self.base_url}/organizations/by-inn/{inn}", timeout=10)
            if response.status_code == 200:
                return response.json().get("data")
            return None
        except:
            return None
    
